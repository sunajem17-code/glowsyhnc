const test = require('node:test')
const assert = require('node:assert/strict')
const { APPEARANCE_ADVICE_GUIDANCE } = require('./appearanceAdviceGuidance')

test('appearance guidance gives direct, simple and actionable Pros and Cons rules', () => {
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /speak to the person face to face/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /say plainly what is weak, uneven, unclear, or needs work/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /short everyday words/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /haircut|hair/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /eyebrow|brow/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /lips/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /skin/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /one direct Try step/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /at least five further distinct improvement findings/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /below 8\.0/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /A haircut or facial-hair change is not a fix for chin projection/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /A low cheekbone score means cheekbone prominence is less favorable/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /there is no fixed maximum/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /do not mention the photo, camera, lighting, angle, image quality, or retaking it/i)
  assert.match(APPEARANCE_ADVICE_GUIDANCE, /do not diagnose lazy eye/i)
  assert.doesNotMatch(APPEARANCE_ADVICE_GUIDANCE, /try a lower camera angle/i)
})
